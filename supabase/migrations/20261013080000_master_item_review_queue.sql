-- Track newly created ITEM master data for post-entry review by KA IPSRS.
-- Reports remain saveable immediately; this queue is independent from report status.
CREATE TABLE IF NOT EXISTS public.master_item_review_queue (
  review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  master_data_id bigint NOT NULL UNIQUE REFERENCES public.master_data(id) ON DELETE CASCADE,
  item_name text NOT NULL,
  area_name text NOT NULL,
  submitted_by_staff_id text,
  submitted_by_name text,
  submitted_by_role text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'MENUNGGU'
    CHECK (status IN ('MENUNGGU','SESUAI','PERLU_KOREKSI','DITOLAK')),
  checked_by_staff_id text,
  checked_by_name text,
  checked_at timestamptz,
  review_note text,
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.master_item_review_queue ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.master_item_review_queue FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.queue_new_master_item_for_review()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_area text;
  v_staff_id text;
  v_staff_name text;
  v_staff_role text;
BEGIN
  IF NEW.data_type <> 'ITEM' THEN RETURN NEW; END IF;
  SELECT name INTO v_area
  FROM public.master_data
  WHERE id = NEW.parent_id AND data_type = 'AREA';
  SELECT staff_id, nama, role
  INTO v_staff_id, v_staff_name, v_staff_role
  FROM public.staff
  WHERE auth_user_id = NEW.created_by AND status = 'Aktif'
  LIMIT 1;
  INSERT INTO public.master_item_review_queue
    (master_data_id,item_name,area_name,submitted_by_staff_id,submitted_by_name,submitted_by_role)
  VALUES
    (NEW.id, NEW.name, COALESCE(v_area,'(area tidak ditemukan)'), v_staff_id, v_staff_name, v_staff_role)
  ON CONFLICT (master_data_id) DO NOTHING;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.queue_new_master_item_for_review() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_queue_new_master_item_for_review ON public.master_data;
CREATE TRIGGER trg_queue_new_master_item_for_review
AFTER INSERT ON public.master_data
FOR EACH ROW EXECUTE FUNCTION public.queue_new_master_item_for_review();
