-- A genuine employment reactivation resets the monitoring anchor. Only an
-- LHI-caused individual block is cleared; global block is never touched here.
CREATE OR REPLACE FUNCTION public.track_staff_employment_status_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_reactivated boolean;
  v_actor_user_id uuid;
  v_actor_staff_id text;
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NEW.status IS NULL OR NEW.status NOT IN ('Aktif', 'Nonaktif') THEN
      RAISE EXCEPTION 'Status kepegawaian hanya boleh Aktif atau Nonaktif. Status akses LHI dikelola terpisah.';
    END IF;

    v_reactivated := lower(COALESCE(OLD.status, '')) IN ('nonaktif', 'nonaktif_lhi_hari_8', 'diblokir_lhi_7_hari')
      AND lower(COALESCE(NEW.status, '')) = 'aktif';

    v_actor_user_id := NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid;
    SELECT s.staff_id INTO v_actor_staff_id
    FROM public.staff s
    WHERE s.auth_user_id = v_actor_user_id
    LIMIT 1;

    IF v_reactivated THEN
      NEW.lhi_active_since := clock_timestamp();
      NEW.lhi_active_since_source := 'EMPLOYMENT_REACTIVATION';
      NEW.lhi_active_since_verified_at := clock_timestamp();
      IF OLD.lhi_access_status = 'BLOCKED_LHI'
         AND OLD.lhi_access_block_reason = 'LHI_NONCOMPLIANCE' THEN
        NEW.lhi_access_status := 'NORMAL';
        NEW.lhi_access_blocked_at := NULL;
        NEW.lhi_access_block_reason := NULL;
      END IF;
    END IF;

    INSERT INTO public.staff_employment_status_events (
      staff_id, old_status, new_status, changed_at, changed_by_staff_id,
      change_source, reason, lhi_access_before, lhi_access_after
    ) VALUES (
      NEW.staff_id, OLD.status, NEW.status, clock_timestamp(), v_actor_staff_id,
      CASE WHEN v_actor_staff_id IS NULL THEN 'SYSTEM' ELSE 'ADMIN_UI' END,
      COALESCE(
        NULLIF(current_setting('app.lhi_status_change_reason', true), ''),
        CASE
          WHEN v_reactivated THEN 'Reaktivasi kepegawaian; anchor LHI direset.'
          ELSE 'Alasan perubahan status tidak disertakan oleh sumber perubahan; perlu verifikasi administrator.'
        END
      ),
      OLD.lhi_access_status, NEW.lhi_access_status
    );
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_track_staff_employment_status_change ON public.staff;
CREATE TRIGGER trg_track_staff_employment_status_change
BEFORE UPDATE OF status ON public.staff
FOR EACH ROW EXECUTE FUNCTION public.track_staff_employment_status_change();

