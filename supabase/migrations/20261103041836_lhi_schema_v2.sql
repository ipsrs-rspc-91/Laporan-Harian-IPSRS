CREATE OR REPLACE FUNCTION public.verify_lhi_active_since_v2(
  p_staff_id text,
  p_active_since_date date,
  p_source_reference text,
  p_actor_auth_user_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_now timestamptz := clock_timestamp();
  v_actor public.staff%ROWTYPE;
  v_target public.staff%ROWTYPE;
  v_anchor timestamptz;
BEGIN
  IF p_actor_auth_user_id IS NULL THEN
    RAISE EXCEPTION 'Identitas KA IPSRS wajib diverifikasi oleh server.';
  END IF;
  IF p_staff_id IS NULL OR btrim(p_staff_id) = '' THEN
    RAISE EXCEPTION 'Petugas yang akan diverifikasi wajib dipilih.';
  END IF;
  IF p_active_since_date IS NULL
     OR p_active_since_date > (v_now AT TIME ZONE 'Asia/Jakarta')::date THEN
    RAISE EXCEPTION 'Tanggal mulai aktif tidak valid atau berada di masa depan.';
  END IF;
  IF p_source_reference IS NULL
     OR length(btrim(p_source_reference)) < 3
     OR length(btrim(p_source_reference)) > 300 THEN
    RAISE EXCEPTION 'Nomor/referensi dokumen HR wajib diisi (3–300 karakter).';
  END IF;

  SELECT * INTO v_actor
  FROM public.staff
  WHERE auth_user_id = p_actor_auth_user_id
  FOR SHARE;

  IF NOT FOUND OR v_actor.role <> 'KA_IPSRS' OR v_actor.status <> 'Aktif' THEN
    RAISE EXCEPTION 'Hanya akun KA IPSRS aktif yang dapat memverifikasi tanggal mulai aktif.';
  END IF;

  SELECT * INTO v_target
  FROM public.staff
  WHERE staff_id = p_staff_id
  FOR UPDATE;

  IF NOT FOUND OR v_target.status <> 'Aktif' THEN
    RAISE EXCEPTION 'Hanya petugas dengan status kepegawaian Aktif yang dapat diverifikasi.';
  END IF;

  v_anchor := p_active_since_date::timestamp AT TIME ZONE 'Asia/Jakarta';

  UPDATE public.staff
  SET lhi_active_since = v_anchor,
      lhi_active_since_source = 'HR_CONFIRMED',
      lhi_active_since_verified_at = v_now,
      updated_at = v_now
  WHERE staff_id = p_staff_id;

  INSERT INTO public.lhi_active_since_verifications (
    staff_id, previous_active_since, verified_active_since,
    source_reference, verified_by_staff_id, verified_by_auth_user_id, verified_at
  ) VALUES (
    p_staff_id, v_target.lhi_active_since, v_anchor,
    btrim(p_source_reference), v_actor.staff_id, p_actor_auth_user_id, v_now
  );

  INSERT INTO public.audit_log (
    username, staff_id, action, report_id, keterangan,
    field_changed, old_value, new_value
  ) VALUES (
    v_actor.staff_id, v_actor.staff_id, 'VERIFY_LHI_ACTIVE_SINCE', NULL,
    'KA IPSRS memverifikasi tanggal mulai aktif berdasarkan referensi dokumen HR/master data.',
    'staff.lhi_active_since,lhi_active_since_source,lhi_active_since_verified_at',
    COALESCE(v_target.lhi_active_since::text, 'NULL'),
    v_anchor::text || ' | HR_CONFIRMED | ' || btrim(p_source_reference)
  );

  RETURN jsonb_build_object(
    'ok', true,
    'staff_id', p_staff_id,
    'previous_active_since', v_target.lhi_active_since,
    'lhi_active_since', v_anchor,
    'source', 'HR_CONFIRMED',
    'verified_at', v_now,
    'verified_by_staff_id', v_actor.staff_id
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.verify_lhi_active_since_v2(text,date,text,uuid)
