import assert from "node:assert/strict";

const apiUrl = String(process.env.API_URL || "").replace(/\/$/, "");
const anonKey = process.env.ANON_KEY || "";
const serviceKey = process.env.SERVICE_ROLE_KEY || "";
const resetCode = process.env.LHI_TEST_RESET_CODE || "246810";
const password = process.env.LHI_TEST_PASSWORD || "";
const origin = "http://localhost:3000";

assert.ok(apiUrl && anonKey && serviceKey, "Local Supabase API_URL and keys are required");
assert.ok(password.length >= 24, "LHI_TEST_PASSWORD must be generated by CI");

async function readResponse(response) {
  const text = await response.text();
  try { return text ? JSON.parse(text) : {}; }
  catch { return { raw: text }; }
}
function headers(key = anonKey) {
  return { apikey: key, "Content-Type": "application/json", Origin: origin };
}
async function resetVerify(code, extra = {}) {
  return fetch(apiUrl + "/functions/v1/lhi-reset-verify", {
    method: "POST",
    headers: { ...headers(), "cf-connecting-ip": "127.0.0.1", ...extra },
    body: JSON.stringify({ code }),
  });
}
async function recoveryAction(capability, action) {
  return fetch(apiUrl + "/functions/v1/lhi-recovery-action", {
    method: "POST",
    headers: { ...headers(), Authorization: "Bearer " + capability },
    body: JSON.stringify({ action }),
  });
}

const email = "ka-ipsrs-" + (process.env.GITHUB_RUN_ID || Date.now()) + "@example.test";
const createdResponse = await fetch(apiUrl + "/auth/v1/admin/users", {
  method: "POST",
  headers: { apikey: serviceKey, Authorization: "Bearer " + serviceKey, "Content-Type": "application/json" },
  body: JSON.stringify({ email, password, email_confirm: true }),
});
const user = await readResponse(createdResponse);
assert.equal(createdResponse.status, 200, "Could not create local Auth user: " + JSON.stringify(user));
assert.ok(user.id);

const bindResponse = await fetch(apiUrl + "/rest/v1/staff?staff_id=eq.KA-TEST", {
  method: "PATCH",
  headers: {
    apikey: serviceKey,
    Authorization: "Bearer " + serviceKey,
    "Content-Type": "application/json",
    Prefer: "return=minimal",
  },
  body: JSON.stringify({ auth_user_id: user.id, lhi_access_status: "BLOCKED_LHI", lhi_access_block_reason: "LHI_NONCOMPLIANCE" }),
});
assert.equal(bindResponse.status, 204, "Could not bind Auth user to KA-TEST");

const loginResponse = await fetch(apiUrl + "/auth/v1/token?grant_type=password", {
  method: "POST",
  headers: { apikey: anonKey, "Content-Type": "application/json" },
  body: JSON.stringify({ email, password }),
});
const login = await readResponse(loginResponse);
assert.equal(loginResponse.status, 200, "Supabase Auth password sign-in failed: " + JSON.stringify(login));
assert.ok(login.access_token);

const initialBlockResponse = await fetch(apiUrl + "/functions/v1/lhi-block-status", { headers: headers() });
const initialBlock = await readResponse(initialBlockResponse);
assert.equal(initialBlockResponse.status, 200);
assert.equal(initialBlock.ok, true);
assert.equal(initialBlock.blocked, true);

const badOrigin = await resetVerify(resetCode, { Origin: "https://untrusted.example" });
assert.equal(badOrigin.status, 403);

const badCodeResponse = await resetVerify("000000");
const badCode = await readResponse(badCodeResponse);
assert.equal(badCodeResponse.status, 400);
assert.equal(badCode.valid, false);
assert.equal(badCode.challenge, undefined);

const resetResponse = await resetVerify(resetCode);
const reset = await readResponse(resetResponse);
assert.equal(resetResponse.status, 200, "Reset gate failed: " + JSON.stringify(reset));
assert.equal(reset.valid, true);
assert.ok(reset.challenge);

const codeOnly = await recoveryAction(resetCode, "apiRecoveryStatus");
assert.equal(codeOnly.status, 403, "Reset code alone was accepted as a capability");

const exchangeResponse = await fetch(apiUrl + "/functions/v1/lhi-recovery-exchange", {
  method: "POST",
  headers: { ...headers(), Authorization: "Bearer " + login.access_token },
  body: JSON.stringify({ challenge: reset.challenge }),
});
const exchange = await readResponse(exchangeResponse);
assert.equal(exchangeResponse.status, 200, "KA exchange failed: " + JSON.stringify(exchange));
assert.equal(exchange.role, "KA_IPSRS");
assert.ok(exchange.recovery_capability);

const replay = await fetch(apiUrl + "/functions/v1/lhi-recovery-exchange", {
  method: "POST",
  headers: { ...headers(), Authorization: "Bearer " + login.access_token },
  body: JSON.stringify({ challenge: reset.challenge }),
});
assert.equal(replay.status, 403, "Consumed challenge replay succeeded");

const forbiddenAction = await recoveryAction(exchange.recovery_capability, "apiGetReports");
assert.equal(forbiddenAction.status, 403, "Recovery capability opened an operational action");

const statusResponse = await recoveryAction(exchange.recovery_capability, "apiRecoveryStatus");
const status = await readResponse(statusResponse);
assert.equal(statusResponse.status, 200);
assert.equal(status.incident_status, "LOCKED");

const startResponse = await recoveryAction(exchange.recovery_capability, "apiStartLhiGrace");
const started = await readResponse(startResponse);
assert.equal(startResponse.status, 200, "Atomic Reset failed: " + JSON.stringify(started));
assert.equal(started.status, "GRACE");
assert.equal(started.snapshot_total, 2);
assert.equal(Date.parse(started.deadline_at) - Date.parse(started.started_at), 12 * 60 * 60 * 1000);

const retryResponse = await recoveryAction(exchange.recovery_capability, "apiStartLhiGrace");
const retry = await readResponse(retryResponse);
assert.equal(retryResponse.status, 200);
assert.equal(retry.already_open, true);
assert.equal(retry.deadline_at, started.deadline_at);

const graceResponse = await fetch(apiUrl + "/functions/v1/lhi-block-status", { headers: headers() });
const grace = await readResponse(graceResponse);
assert.equal(graceResponse.status, 200);
assert.equal(grace.blocked, false);
assert.equal(grace.grace_active, true);
assert.equal(grace.grace_deadline_at, started.deadline_at);

console.log("Local Supabase Auth/Edge recovery lifecycle passed.");
